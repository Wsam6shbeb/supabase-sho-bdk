export type TranslationPath = {
  [K1 in keyof AppTranslations]: {
    [K2 in keyof AppTranslations[K1]]: `${K1}.${K2 & string}`;
  }[keyof AppTranslations[K1]];
}[keyof AppTranslations];

// [شرح الدالة: t] يحوّل مفتاح الترجمة إلى النص العربي المقابل له، مع دعم القيم الديناميكية عند الحاجة.
export function t(path: string, params?: Record<string, string | number>): string {
  const parts = path.split('.');
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  let current: any = ar;
  for (const part of parts) {
    if (current && typeof current === 'object' && part in current) {
      current = current[part];
    } else {
      return path;
    }
  }
  let result = typeof current === 'string' ? current : path;

  if (params) {
    for (const [key, value] of Object.entries(params)) {
      result = result.replace(new RegExp(`\\{${key}\\}`, 'g'), String(value));
    }
  }

  return result;
}
